
CREATE TABLE PERSONA (
    ID_PERSONA NUMBER PRIMARY KEY,
    DPI VARCHAR2(20) UNIQUE NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    TELEFONO VARCHAR2(15),
    CORREO VARCHAR2(100)
);

CREATE TABLE CLIENTE (
    ID_PERSONA NUMBER PRIMARY KEY,
    NIT VARCHAR2(20),
    FOREIGN KEY (ID_PERSONA) REFERENCES PERSONA(ID_PERSONA) ON DELETE CASCADE
);

CREATE TABLE MECANICO (
    ID_PERSONA NUMBER PRIMARY KEY,
    ESPECIALIDAD VARCHAR2(50) NOT NULL,
    FOREIGN KEY (ID_PERSONA) REFERENCES PERSONA(ID_PERSONA) ON DELETE CASCADE
);

CREATE TABLE VEHICULO (
    PLACA VARCHAR2(10) PRIMARY KEY,
    MARCA VARCHAR2(50) NOT NULL,
    MODELO VARCHAR2(50) NOT NULL,
    ANIO NUMBER(4) NOT NULL,
    ID_CLIENTE NUMBER NOT NULL,
    FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_PERSONA)
);

CREATE TABLE SERVICIO (
    ID_SERVICIO NUMBER PRIMARY KEY,
    DESCRIPCION VARCHAR2(100) NOT NULL,
    COSTO_MANO_OBRA NUMBER(10,2) CHECK (COSTO_MANO_OBRA >= 0) NOT NULL
);

CREATE TABLE REPUESTO (
    ID_REPUESTO NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    DESCRIPCION VARCHAR2(150),
    PRECIO NUMBER(10,2) CHECK (PRECIO >= 0) NOT NULL,
    CANTIDAD_DISPONIBLE NUMBER(6) CHECK (CANTIDAD_DISPONIBLE >= 0) NOT NULL
);

CREATE TABLE ORDEN_TRABAJO (
    ID_ORDEN NUMBER PRIMARY KEY,
    PLACA_VEHICULO VARCHAR2(10) NOT NULL,
    ID_MECANICO NUMBER NOT NULL,
    PROBLEMA_REPORTADO VARCHAR2(255) NOT NULL,
    ESTADO VARCHAR2(20) CHECK (ESTADO IN ('PENDIENTE', 'EN PROCESO', 'FINALIZADA', 'CANCELADA')) NOT NULL,
    FECHA_CREACION DATE DEFAULT SYSDATE NOT NULL,
    TOTAL_MANO_OBRA NUMBER(10,2) DEFAULT 0.00 NOT NULL,
    TOTAL_REPUESTOS NUMBER(10,2) DEFAULT 0.00 NOT NULL,
    FOREIGN KEY (PLACA_VEHICULO) REFERENCES VEHICULO(PLACA),
    FOREIGN KEY (ID_MECANICO) REFERENCES MECANICO(ID_PERSONA)
);

CREATE TABLE DETALLE_SERVICIO (
    ID_DETALLE NUMBER PRIMARY KEY,
    ID_ORDEN NUMBER NOT NULL,
    ID_SERVICIO NUMBER NOT NULL,
    SUBTOTAL NUMBER(10,2) NOT NULL,
    FOREIGN KEY (ID_ORDEN) REFERENCES ORDEN_TRABAJO(ID_ORDEN) ON DELETE CASCADE,
    FOREIGN KEY (ID_SERVICIO) REFERENCES SERVICIO(ID_SERVICIO)
);

CREATE TABLE DETALLE_REPUESTO (
    ID_DETALLE NUMBER PRIMARY KEY,
    ID_ORDEN NUMBER NOT NULL,
    ID_REPUESTO NUMBER NOT NULL,
    CANTIDAD NUMBER(4) CHECK (CANTIDAD > 0) NOT NULL,
    PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
    SUBTOTAL NUMBER(10,2) NOT NULL,
    FOREIGN KEY (ID_ORDEN) REFERENCES ORDEN_TRABAJO(ID_ORDEN) ON DELETE CASCADE,
    FOREIGN KEY (ID_REPUESTO) REFERENCES REPUESTO(ID_REPUESTO)
);


